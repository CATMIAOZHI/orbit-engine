package com.cefrium;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks API that may still change, or go, in a later release without the
 * deprecation period the rest of the API gets: new API until a release has
 * shipped it unchanged, and API kept for desktop CEF parity that no app has
 * been seen to need. Not covered by the 1.0 freeze.
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target({ElementType.TYPE, ElementType.METHOD, ElementType.CONSTRUCTOR, ElementType.FIELD})
public @interface CefriumExperimental {}
